writeFileSync(targetPath, content, { encoding: 'utf8', mode: 0o600 });
try { chmodSync(targetPath, 0o600); } catch { /* Windows ACLs are managed separately. */ }
console.log('Created .env.production with fresh database, JWT, and webhook secrets. Secret values were not printed.');

function readArgument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? undefined : process.argv[index + 1];
}

function normalizeHttpsOrigin(value, name) {
  const url = new URL(value);
  if (url.protocol !== 'https:' || url.username || url.password || url.search || url.hash || url.pathname !== '/') {
    throw new Error(`${name} must be an HTTPS origin without credentials, path, query, or fragment.`);
  }
  return url.origin;
}

function normalizeHttpsUrl(value, name) {
  const url = new URL(value);
  if (url.protocol !== 'https:' || url.username || url.password || url.search || url.hash) {
    throw new Error(`${name} must be an HTTPS URL without credentials, query, or fragment.`);
  }
  return url.toString().replace(/\/$/, '');
}

function encodeValue(value) {
  if (/^[A-Za-z0-9_./:@?&=+,-]*$/.test(value)) return value;
  return JSON.stringify(value);
}
