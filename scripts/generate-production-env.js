import { randomBytes } from 'node:crypto';
import { chmodSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { parse } from 'dotenv';

const sourcePath = resolve('.env');
const targetPath = resolve('.env.production');
const source = parse(readFileSync(sourcePath));

const publicUrl = readArgument('--public-url') ?? process.env.DEPLOY_PUBLIC_URL;
if (!publicUrl) {
  throw new Error('Pass --public-url https://<backend-host> after the Oracle public IP or DNS name is known.');
}

const backendOrigin = normalizeHttpsOrigin(publicUrl, '--public-url');
const frontendOrigin = normalizeHttpsOrigin('https://shop-front-mocha.vercel.app', 'frontend URL');
const databasePassword = randomBytes(36).toString('base64url');

